"""Password hashing and JWT login.

Flow: /login checks the password and hands out a token (create_token). The client
sends it with every request in the header `Authorization: Bearer <token>`.
Routes with `user: CurrentUser` run get_current_user first, which checks the token
and loads the user.
"""

import os
from datetime import datetime, timedelta, timezone
from typing import Annotated

import jwt
from fastapi import Depends, HTTPException
from fastapi.security import OAuth2PasswordBearer
from pwdlib import PasswordHash

from db import SessionLocal
from models import User

# Signs the tokens. Whoever knows it can make valid tokens, so it lives in .env
# (on Render: generated by Render). Without it the app doesn't start.
SECRET_KEY = os.environ["SECRET_KEY"]
ALGORITHM = "HS256"
# After 30 minutes a token is invalid and the user logs in again.
TOKEN_MINUTES = 30

# The currently recommended hash algorithm (Argon2). A hash can't be turned back
# into the password; a leaked DB doesn't leak the passwords.
password_hash = PasswordHash.recommended()
# Reads the token from the Authorization header. tokenUrl tells /docs where the
# Authorize button logs in.
oauth2_scheme = OAuth2PasswordBearer(tokenUrl="login")


def hash_password(password: str) -> str:
    return password_hash.hash(password)


# Hashes the typed password the same way and compares it with the stored hash.
def verify_password(password: str, hashed: str) -> bool:
    return password_hash.verify(password, hashed)


def create_token(user_id: int) -> str:
    expires = datetime.now(timezone.utc) + timedelta(minutes=TOKEN_MINUTES)
    # "sub" (subject) = who the token is for. "exp" = when it expires; jwt.decode
    # checks it. The token is signed, not encrypted: anyone can read it, but nobody
    # can change it without SECRET_KEY.
    return jwt.encode({"sub": str(user_id), "exp": expires}, SECRET_KEY, ALGORITHM)


def get_current_user(token: Annotated[str, Depends(oauth2_scheme)]) -> User:
    try:
        # Fails if the signature is wrong, the token is broken or expired.
        user_id = int(jwt.decode(token, SECRET_KEY, algorithms=[ALGORITHM])["sub"])
    except jwt.InvalidTokenError:
        raise HTTPException(status_code=401, detail="invalid token")
    with SessionLocal() as session:
        user = session.get(User, user_id)
    # A valid token of a user that was deleted since (DELETE /me).
    if user is None:
        raise HTTPException(status_code=401, detail="invalid token")
    return user


# Shortcut for routes: `user: CurrentUser` = "run get_current_user, give me the user".
CurrentUser = Annotated[User, Depends(get_current_user)]
